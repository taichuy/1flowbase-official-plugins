export function errorText(code: string, t: Copy): string {
  const map: Record<string, string> = {
    oauth_not_configured: t.errUnconfigured,
    invalid_input: t.errInvalidInput,
    invalid_redirect_uri: t.errInvalidInput,
    client_secret_required: t.errClientSecretReq,
    oauth_state_expired: t.errStateExpired,
    oauth_state_invalid: t.errStateExpired,
    oauth_actor_mismatch: t.errActorMismatch,
    reauth_account_mismatch: t.errReauthMismatch,
    google_refresh_token_missing: t.errNoRefreshToken,
    google_reauth_required: t.errReauthRequired,
    google_quota_exceeded: t.errQuota,
    google_permission_denied: t.errPermission,
    scope_upgrade_required: t.errScopeUpgrade,
    account_disabled: t.errDisabled,
    google_network_error: t.errNetwork,
    google_oauth_cancelled: t.errCancelled,
    forbidden: t.forbidden,
    permission_denied: t.forbidden,
  };
  return map[code] ?? t.errGeneric;
}

