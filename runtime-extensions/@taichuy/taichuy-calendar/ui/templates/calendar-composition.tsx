function EditableAIHelper({ data, locale }: { data: ChartAIHelperData; locale: 'zh' | 'en' }) {
  const { token } = theme.useToken();
  const copy = assistantCopy[locale];
  const { styles } = useStyles();
  return (
    <Card data-calendar-ai-helper={data.kind} className={styles.assistantCard}
      title={data.kind === 'ziwei' ? 'AI 解读助手 (紫微斗数)' : 'AI解读助手(八字排盘)'}
      style={{ marginTop: 24, background: token.colorFillAlter }}
      extra={<Flex wrap gap={8}>
        <Button icon={<CopyOutlined />} onClick={data.copyNatal}>
          {data.kind === 'ziwei' ? '复制本命数据' : '一键复制完整数据'}
        </Button>
        {data.kind === 'ziwei' && <Button type="primary" icon={<FileTextOutlined />} onClick={data.copyHoroscope}>复制运限数据</Button>}
      </Flex>}
    >
      <blockquote style={{ margin: '0 0 16px', padding: '12px 16px', borderLeft: `4px solid ${token.colorPrimary}`,
        background: token.colorFillQuaternary, color: token.colorTextSecondary, fontStyle: 'italic', lineHeight: 1.8 }}>
        {copy.quote.map((line, index) => <p key={index} style={{ margin: 0 }}>{line}</p>)}
      </blockquote>
      <p style={{ color: token.colorTextSecondary }}>{copy.instruction}</p>
      <Input.TextArea aria-label="排盘数据" value={data.natalText} readOnly autoSize={{ minRows: 4, maxRows: 10 }}
        style={{ fontFamily: 'monospace' }} />
      <p style={{ fontSize: 12, color: token.colorTextDescription, lineHeight: 1.5, whiteSpace: 'pre-wrap' }}>{copy.tips}</p>
    </Card>
  );
}

